def transform_svg(svg: str) -> str:
    """Apply the Neon Cyber-Circuit styling to a Platane/snk SVG string."""
    if 'id="cyber-circuit-edition"' in svg:
        return svg

    if "<style>" not in svg or "</style>" not in svg:
        raise ValueError("Input does not look like a Platane/snk SVG (<style> missing)")

    # 1. Expand viewBox slightly for the header & framed circuit card
    svg = re.sub(
        r'<svg\b[^>]*>',
        '<svg viewBox="-20 -48 888 193" width="888" height="193" xmlns="http://www.w3.org/2000/svg">',
        svg,
        count=1,
    )

    # 2. Replace :root palette variables and append cyber-circuit CSS rules
    s3_match = re.search(r"\.s\.s3\{[^}]*?(transform:[^;\}]+)", svg)
    s4_transform = f"{s3_match.group(1)};" if s3_match else "transform:translate(48px,-16px);"
    extra_css = EXTRA_CSS.replace("__S4_TRANSFORM__", s4_transform)

    svg = re.sub(r":root\{[^}]*\}", ROOT_VARS, svg, count=1)
    svg = svg.replace("</style>", extra_css + "</style>", 1)

    # 3. Inject <defs> and background circuit frame right after </style>
    style_end = svg.index("</style>") + len("</style>")
    header_part = svg[:style_end]
    body_part = svg[style_end:]
    if not body_part.endswith("</svg>"):
        raise ValueError("Input SVG missing closing </svg>")
    inner_body = body_part[:-6]

    # 4. Slightly rounder contribution cells + wrap grid and snake in playfield clip
    inner_body = re.sub(
        r'(<rect class="c[^"]*"[^>]*?)rx="2" ry="2"/>',
        r'\1rx="2.5" ry="2.5"/>',
        inner_body,
    )

    # 5. Restyle progress bars (.u) into a thin 3px circuit line connected to the grid
    def _restyle_u(match: re.Match[str]) -> str:
        tag = match.group(0)
        tag = re.sub(r'height="[^"]+"', 'height="3"', tag)
        tag = re.sub(r'y="[^"]+"', 'y="128"', tag)
        if "rx=" not in tag:
            tag = tag[:-2] + ' rx="1.5" ry="1.5"/>'
        return tag

    inner_body = re.sub(r'<rect class="u [^"]*"[^>]*/>', _restyle_u, inner_body)

    # 6. Upgrade snake head, add subtle body glow, and add fading trailing node s4
    inner_body = re.sub(
        r'<rect class="s s0"[^>]*/>',
        SNAKE_HEAD_GROUP,
        inner_body,
        count=1,
    )
    inner_body = re.sub(
        r'(<rect class="s s1"[^>]*)(/>)',
        r'\1 filter="url(#body-glow)"\2',
        inner_body,
        count=1,
    )
    if 'class="s s3"' in inner_body and 'class="s s4"' not in inner_body:
        inner_body += '<rect class="s s4" x="4.2" y="4.2" width="7.6" height="7.6" rx="2.6" ry="2.6"/>'

    # Separate playfield (cells + snake) from bottom .u activity bar so playfield-clip
    # hides parked off-grid snake segments above y=0 without clipping the activity bar.
    u_tags = "".join(re.findall(r'<rect class="u [^"]*"[^>]*/>', inner_body))
    playfield = re.sub(r'<rect class="u [^"]*"[^>]*/>', "", inner_body)

    out = (
        f"{header_part}"
        f"{DEFS_BLOCK}"
        f"{CHROME_BACK}"
        f'<g clip-path="url(#playfield-clip)">{playfield}</g>'
        f"{u_tags}"
        f"</svg>"
    )
    ET.fromstring(out)  # verify well-formed XML
    return out


def main(argv: list[str]) -> int:
    if len(argv) < 2:
        print("Usage: python scripts/cyber_snake.py <svg_path> [<svg_path> ...]", file=sys.stderr)
        return 2

    for raw in argv[1:]:
        path = Path(raw)
        if not path.exists():
            print(f"Missing file: {path}", file=sys.stderr)
            return 1
        updated = transform_svg(path.read_text(encoding="utf-8"))
        path.write_text(updated, encoding="utf-8")
        print(f"Transformed {path} ({len(updated)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
